-- Create and switch to project schema
CREATE SCHEMA IF NOT EXISTS LOOPCRAFT_ANALYTICS;
OPEN SCHEMA LOOPCRAFT_ANALYTICS;

-- 1. Knowledge Base Articles Table
CREATE OR REPLACE TABLE KB_ARTICLES (
    article_id          VARCHAR(64) PRIMARY KEY,
    title               VARCHAR(255) NOT NULL,
    category            VARCHAR(64) NOT NULL,
    content_text        VARCHAR(2000000),
    version             DECIMAL(4, 1) DEFAULT 1.0,
    author              VARCHAR(128) DEFAULT 'System',
    last_updated        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_views         INTEGER DEFAULT 0,
    deflection_rate     DECIMAL(5, 2) DEFAULT 0.00,
    escalation_count    INTEGER DEFAULT 0,
    status              VARCHAR(32) DEFAULT 'PUBLISHED' -- 'PUBLISHED', 'NEEDS_REVIEW', 'ARCHIVED'
);

-- 2. Support Tickets Table
CREATE OR REPLACE TABLE SUPPORT_TICKETS (
    ticket_id           VARCHAR(64) PRIMARY KEY,
    requester_id        VARCHAR(64) NOT NULL,
    category            VARCHAR(64) NOT NULL,
    subject             VARCHAR(255) NOT NULL,
    query_text          VARCHAR(2000000) NOT NULL,
    resolution_notes    VARCHAR(2000000),
    status              VARCHAR(32) DEFAULT 'RESOLVED',
    priority            VARCHAR(16) DEFAULT 'MEDIUM',
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at         TIMESTAMP
);

-- 3. AI Agent Interactions & Feedback Log (High-velocity telemetry)
CREATE OR REPLACE TABLE AI_INTERACTIONS (
    interaction_id      VARCHAR(64) PRIMARY KEY,
    ticket_id           VARCHAR(64),
    session_id          VARCHAR(64),
    user_query          VARCHAR(2000000) NOT NULL,
    bot_response        VARCHAR(2000000) NOT NULL,
    kb_article_id       VARCHAR(64),
    rating              INTEGER NOT NULL, -- +1 = Thumbs Up, -1 = Thumbs Down, 0 = Neutral
    feedback_reason     VARCHAR(255),
    latency_ms          DECIMAL(8, 2),
    confidence_score    DECIMAL(4, 3),
    escalated_to_human  BOOLEAN DEFAULT FALSE,
    interaction_time    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interaction_article FOREIGN KEY (kb_article_id) REFERENCES KB_ARTICLES (article_id)
);

-- 4. Closed-Loop Feedback Diagnostics (Auto-generated by LoopCraft supervisor)
CREATE OR REPLACE TABLE FEEDBACK_DIAGNOSTICS (
    diagnostic_id       VARCHAR(64) PRIMARY KEY,
    interaction_id      VARCHAR(64) NOT NULL,
    failure_type        VARCHAR(64) NOT NULL, -- 'STALE_ARTICLE', 'NO_COVERAGE', 'WRONG_INTENT'
    root_cause          VARCHAR(1000) NOT NULL,
    proposed_fix_title  VARCHAR(255),
    proposed_kb_content VARCHAR(2000000),
    status              VARCHAR(32) DEFAULT 'QUEUED_FOR_REVIEW', -- 'QUEUED_FOR_REVIEW', 'APPROVED', 'DISCARDED'
    reviewed_by         VARCHAR(128),
    reviewed_at         TIMESTAMP,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_diagnostic_interaction FOREIGN KEY (interaction_id) REFERENCES AI_INTERACTIONS (interaction_id)
);

-- ==============================================================================
-- ANALYTICAL VIEWS POWERED BY EXASOL IN-MEMORY COLUMNAR ENGINE
-- ==============================================================================

-- View 1: Real-time Deflection Rate & Failure Audit per KB Article
CREATE OR REPLACE VIEW V_KB_HEALTH_AUDIT AS
SELECT 
    k.article_id,
    k.title,
    k.category,
    k.deflection_rate AS current_deflection_rate,
    COUNT(i.interaction_id) AS total_conversations,
    SUM(CASE WHEN i.rating = -1 THEN 1 ELSE 0 END) AS negative_ratings,
    SUM(CASE WHEN i.rating = 1 THEN 1 ELSE 0 END) AS positive_ratings,
    ROUND(
        CASE 
            WHEN COUNT(i.interaction_id) = 0 THEN 0.00
            ELSE (SUM(CASE WHEN i.rating = 1 THEN 1 ELSE 0 END) * 100.0) / COUNT(i.interaction_id)
        END, 2
    ) AS calculated_accuracy_pct,
    COUNT(d.diagnostic_id) AS pending_corrections
FROM KB_ARTICLES k
LEFT JOIN AI_INTERACTIONS i ON k.article_id = i.kb_article_id
LEFT JOIN FEEDBACK_DIAGNOSTICS d ON i.interaction_id = d.interaction_id AND d.status = 'QUEUED_FOR_REVIEW'
GROUP BY k.article_id, k.title, k.category, k.deflection_rate;

-- View 2: Failure Category Distribution
CREATE OR REPLACE VIEW V_FAILURE_BREAKDOWN AS
SELECT 
    d.failure_type,
    COUNT(*) AS total_failures,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS percentage_share,
    COUNT(CASE WHEN d.status = 'APPROVED' THEN 1 END) AS resolved_count,
    COUNT(CASE WHEN d.status = 'QUEUED_FOR_REVIEW' THEN 1 END) AS pending_count
FROM FEEDBACK_DIAGNOSTICS d
GROUP BY d.failure_type;

-- View 3: Deflection Recovery Trend (Before vs After KB Update)
CREATE OR REPLACE VIEW V_DEFLECTION_RECOVERY AS
SELECT 
    DATE_TRUNC('hour', i.interaction_time) AS interaction_hour,
    i.kb_article_id,
    k.title,
    COUNT(*) AS query_volume,
    ROUND(AVG(CASE WHEN i.rating = 1 THEN 1.0 ELSE 0.0 END) * 100, 1) AS hourly_deflection_rate,
    ROUND(AVG(i.latency_ms), 1) AS avg_latency_ms
FROM AI_INTERACTIONS i
JOIN KB_ARTICLES k ON i.kb_article_id = k.article_id
GROUP BY DATE_TRUNC('hour', i.interaction_time), i.kb_article_id, k.title;

